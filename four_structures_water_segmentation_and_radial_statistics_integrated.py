def run_segment(args: argparse.Namespace) -> tuple[np.ndarray, Path]:
    raw_rgb = read_rgb(args.input)
    height, width = raw_rgb.shape[:2]
    pillar_mask, ref_width, ref_height = get_structure_pillar_mask(args.structure)
    verify_exact_shape(width, height, ref_width, ref_height)
    analysis_mask = quarter_circle_mask(height, width, radius=args.analysis_radius)

    if args.structure == 4 and args.structure4_mode == "v6":
        labels = segment_structure4_v6(
            raw_rgb=raw_rgb,
            pillar_mask=pillar_mask,
        )
        print("Structure 4 segmentation mode: v6 strict conservative rule")
    else:
        labels = segment_from_raw(
            raw_rgb=raw_rgb,
            pillar_mask=pillar_mask,
            analysis_mask=analysis_mask,
            gray_threshold=args.gray_threshold,
            texture_threshold=args.texture_threshold,
            texture_window=args.texture_window,
        )
        if args.structure == 4:
            print("Structure 4 segmentation mode: generic")

    output_dir: Path = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    rendered = render_labels(labels)
    overlay = create_overlay(raw_rgb, rendered)

    save_rgb(output_dir / "three_class_segmentation.png", rendered)
    save_rgb(output_dir / "review_overlay.png", overlay)
    save_mask(output_dir / "liquid_phase_mask.png", labels == 0)
    save_mask(output_dir / "pillar_mask.png", labels == 1)
    save_mask(output_dir / "gas_and_inlet_mask.png", labels == 2)
    np.save(output_dir / "three_class_labels.npy", labels)

    if args.export_template:
        np.savez_compressed(
            output_dir / "approved_template_labels_export.npz",
            labels=labels.astype(np.uint8),
            reference_width=np.asarray(labels.shape[1], dtype=np.int32),
            reference_height=np.asarray(labels.shape[0], dtype=np.int32),
            blue_rgb=BLUE_RGB,
            gray_rgb=GRAY_RGB,
            white_rgb=WHITE_RGB,
        )

    liquid_pixels = int(np.count_nonzero((labels == 0) & (analysis_mask > 0)))
    gas_pixels = int(np.count_nonzero((labels == 2) & (analysis_mask > 0)))
    pore_pixels = liquid_pixels + gas_pixels
    saturation = np.nan if pore_pixels == 0 else liquid_pixels / pore_pixels * 100.0

    print(f"Structure: {args.structure}")
    print(f"Input dimensions: {width} x {height}")
    print(f"Liquid pixels: {liquid_pixels}")
    print(f"Gas pixels: {gas_pixels}")
    print("Pore-water saturation: NA" if np.isnan(saturation) else f"Pore-water saturation: {saturation:.2f}%")
    print(f"Output directory: {output_dir}")
    return labels, output_dir


