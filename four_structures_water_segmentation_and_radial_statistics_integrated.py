def parse_radius_edges(values: list[str] | None) -> list[int]:
    if values is None or len(values) == 0:
        return DEFAULT_RADIUS_EDGES
    edges = [int(v) for v in values]
    if len(edges) < 2:
        raise ValueError("radius_edges must contain at least two values.")
    if sorted(edges) != edges:
        raise ValueError("radius_edges must be sorted in ascending order.")
    return edges


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Integrated four-structure water segmentation and seven-region radial analysis")
    subparsers = parser.add_subparsers(dest="command", required=True)

    p0 = subparsers.add_parser("render-template", help="Render the built-in complete template (currently available for structure 1)")
    p0.add_argument("--structure", type=int, choices=(1, 2, 3, 4), required=True)
    p0.add_argument("--output-dir", type=Path, required=True)

    def add_segment_args(p):
        p.add_argument("--input", type=Path, required=True)
        p.add_argument("--structure", type=int, choices=(1, 2, 3, 4), required=True)
        p.add_argument("--output-dir", type=Path, required=True)
        p.add_argument("--gray-threshold", type=int, default=135)
        p.add_argument("--texture-threshold", type=float, default=18.0)
        p.add_argument("--texture-window", type=int, default=15)
        p.add_argument("--analysis-radius", type=int, default=560)
        p.add_argument(
            "--structure4-mode",
            choices=("v6", "generic"),
            default="v6",
            help=(
                "Structure 4 uses the final approved v6 strict conservative identification rule by default; "
                "select generic only when testing the previous general thresholding method."
            ),
        )
        p.add_argument("--export-template", action="store_true")
        p.add_argument("--radius-edges", nargs="*", default=None)

    p1 = subparsers.add_parser("segment", help="Generate a three-class segmentation from the raw bright-field image")
    add_segment_args(p1)

    p2 = subparsers.add_parser("segment-analyze", help="Segment first, then perform statistics for the seven radial regions")
    add_segment_args(p2)

    p_run = subparsers.add_parser(
        "run",
        help="Use the raw image directly and output the segmentation, radial data, and total data",
    )
    add_segment_args(p_run)

    p3 = subparsers.add_parser("analyze", help="Perform statistics for the seven radial regions on an existing three-class result")
    p3.add_argument("--segmentation", type=Path, required=True, help="Can be a three-class PNG / NPY / NPZ")
    p3.add_argument("--output-dir", type=Path, required=True)
    p3.add_argument("--radius-edges", nargs="*", default=None)

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if hasattr(args, "radius_edges"):
        args.radius_edges = parse_radius_edges(args.radius_edges)

    if args.command == "render-template":
        run_render_template(args)
    elif args.command == "segment":
        run_segment(args)
    elif args.command in ("segment-analyze", "run"):
        run_segment_analyze(args)
    elif args.command == "analyze":
        run_analyze(args)
    else:
        raise ValueError(f"Unknown command: {args.command}")


if __name__ == "__main__":
    main()